def get_locale():
    requested = request.args.get('lang') if request else None
    if requested and requested[:2].lower() in SUPPORTED_LANGUAGES:
        return requested[:2].lower()

    header = request.headers.get('Accept-Language', '') if request else ''
    for chunk in header.split(','):
        code = chunk.split(';')[0].strip()[:2].lower()
        if code in SUPPORTED_LANGUAGES:
            return code

    return DEFAULT_LANGUAGE


def translate(key, locale=None, **params):
    language = locale or DEFAULT_LANGUAGE
    try:
        language = locale or get_locale()
    except RuntimeError:
        pass

    catalog = MESSAGES.get(language, MESSAGES[DEFAULT_LANGUAGE])
    text = catalog.get(key) or MESSAGES[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**params) if params else text


